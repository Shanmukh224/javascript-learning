//forloop
for (let i = 1; i <= 5; i++) {
    console.log(i);
}

//Backwards
for (let i = 5; i >= 1; i--) {
    console.log(i);
}

//whileloop
let i = 1;

while (i <= 5) {
    console.log(i);
    i++;
}

//LoopThroughAnArray
let fruits = ["Apple", "Banana", "Mango"];

for (let i = 0; i < fruits.length; i++) {
    console.log(fruits[i]);
}

//forAndOfLoop
let fruits = ["Apple", "Banana", "Mango"];

for (let fruit of fruits) {
    console.log(fruit);
}

