let a = 10;
let b = 5;

// Arithmetic operators

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// Assignment operators

let x = 10;

x += 5;
console.log(x);

x -= 3;
console.log(x);

x *= 2;
console.log(x);

x /= 4;
console.log(x);

// Comparison operators

console.log(10 > 5);
console.log(10 < 5);
console.log(10 >= 10);
console.log(10 <= 10);
console.log(10 == "10");
console.log(10 === "10");
console.log(10 != 5);
console.log(10 !== "10");

// Logical operators

let age = 20;
let hasID = true;

console.log(age >= 18 && hasID);
console.log(age >= 18 || hasID);
console.log(!hasID);